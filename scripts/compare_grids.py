#!/usr/bin/env python3

import argparse
import csv
import sys
from pathlib import Path

REPO_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_DIR / "scripts"))
import estimate_cost  # noqa: E402

BUDGET_LOGROWS = 21
logrows_est = estimate_cost.logrows_estimate
MAX_CIRCUIT_LOGROWS = estimate_cost.MAX_PUBLIC_SRS
MAX_PUBLIC_SRS = estimate_cost.EZKL_MAX_PUBLIC_SRS


def tier_of(num_rows: int) -> int:
    return max(
        estimate_cost.MIN_LOGROWS,
        (num_rows + estimate_cost.RESERVED_BLINDING_ROWS - 1).bit_length(),
    )


def load(path: Path) -> dict:
    rows = {}
    with path.open(newline="") as f:
        for r in csv.DictReader(f):
            if r["status"] != "OK" or not r.get("num_rows"):
                continue
            rows[r["name"]] = r
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--baseline", default=str(REPO_DIR / "results/grid/grid.csv"))
    ap.add_argument(
        "--optimized", default=str(REPO_DIR / "results/grid_optimized/grid.csv")
    )
    ap.add_argument("--out", default=str(REPO_DIR / "docs/recon/06_tier_crossing.md"))
    args = ap.parse_args()

    base = load(Path(args.baseline))
    opt = load(Path(args.optimized))
    shared = sorted(set(base) & set(opt))
    if not shared:
        sys.exit("no configs measured OK in both grids")

    joined = []
    for name in shared:
        b, o = base[name], opt[name]
        nb, no = int(b["num_rows"]), int(o["num_rows"])
        lb, lo = tier_of(nb), tier_of(no)
        joined.append(
            {
                "name": name,
                "d_model": int(b["d_model"]),
                "seq_len": int(b["seq_len"]),
                "n_layers": int(b["n_layers"]),
                "rows_base": nb,
                "rows_opt": no,
                "cut_pct": 100.0 * (nb - no) / nb,
                "logrows_base": lb,
                "logrows_opt": lo,
                "tiers_dropped": lb - lo,
                "cost_model_logrows_base": logrows_est(nb),
                "cost_model_logrows_opt": logrows_est(no),
            }
        )
    joined.sort(key=lambda r: -r["rows_base"])

    crossed = [r for r in joined if r["tiers_dropped"] > 0]
    within_limit = [r for r in crossed if r["logrows_base"] <= MAX_CIRCUIT_LOGROWS]
    enter_limit = [
        r
        for r in crossed
        if r["logrows_base"] > MAX_CIRCUIT_LOGROWS >= r["logrows_opt"]
    ]
    above_limit = [r for r in crossed if r["logrows_opt"] > MAX_CIRCUIT_LOGROWS]
    rescued = [
        r for r in joined if r["logrows_base"] > BUDGET_LOGROWS >= r["logrows_opt"]
    ]
    near_tier_base = [
        r
        for r in joined
        if r["rows_base"]
        / (2 ** (r["logrows_base"] - 1) - estimate_cost.RESERVED_BLINDING_ROWS)
        <= 1.20
    ]

    cuts = [r["cut_pct"] for r in joined]
    L = []
    L.append("# Rescale optimization: row counts and tier crossings\n")
    L.append(
        "Generated by `scripts/compare_grids.py`. Both grids are real "
        "`gen-settings` measurements, joined by configuration name. "
        "The optimized-grid experiment uses `EZKL_DIV_ROUND_NEAREST=1 "
        "EZKL_RESCALE_FUSION=1`. Row counts alone do not establish "
        "successful setup/prove/verify or measured memory savings.\n"
    )
    L.append(
        f"Configurations measured OK in both grids: **{len(joined)}**. "
        f"Row reduction ranges **{min(cuts):.1f}% to {max(cuts):.1f}%** "
        f"(mean {sum(cuts)/len(cuts):.1f}%).\n"
    )

    L.append("## Tier crossings\n")
    L.append(
        f"**{len(crossed)} of {len(joined)} configurations drop at least one "
        f"`logrows` tier.** Within the fitted domain, the cost model "
        "predicts approximately a factor of two per tier in proving time "
        "and peak memory (`docs/recon/05_cost_model.md`). These predictions "
        "are separate from end-to-end measurements.\n"
    )
    L.append(
        f"The public SRS supports `k <= {MAX_PUBLIC_SRS}`. This circuit "
        f"family is representable only at `k <= {MAX_CIRCUIT_LOGROWS}`: "
        "constraint degree 6 requires an extended domain of k+3 bits, "
        "while BN254 has 2-adicity 28 (see `results/k26_keygen_probe/`). "
        "Tier counting uses unclamped row requirements.\n"
    )
    L.append(
        f"- **{len(within_limit)}** drops have both tiers within the circuit limit."
    )
    L.append(f"- **{len(enter_limit)}** drops enter the representable range.")
    L.append(f"- **{len(above_limit)}** drops remain above the circuit limit.\n")
    if enter_limit:
        L.append("### Configurations entering the representable range\n")
        L.append("| config | rows (base -> opt) | cut | tier |")
        L.append("|---|---|---|---|")
        for r in enter_limit:
            L.append(
                f"| {r['name']} (L{r['n_layers']}) | {r['rows_base']:,} -> "
                f"{r['rows_opt']:,} | {r['cut_pct']:.1f}% | "
                f"{r['logrows_base']} -> {r['logrows_opt']} |"
            )
        L.append("")
    if crossed:
        L.append(
            "| config | rows (base -> opt) | cut | logrows | tiers | est. prove RSS (base -> opt) |"
        )
        L.append("|---|---|---|---|---|---|")
        for r in crossed:
            rss = []
            for side in ("base", "opt"):
                k = r[f"logrows_{side}"]
                if k > MAX_CIRCUIT_LOGROWS:
                    rss.append(f"N/A (not representable at k={k})")
                else:
                    e = estimate_cost.estimate(r[f"rows_{side}"])
                    rss.append(f"{e.prove_rss_mb/1024:,.0f} GiB")
            L.append(
                f"| {r['name']} (L{r['n_layers']}) | {r['rows_base']:,} -> {r['rows_opt']:,} "
                f"| {r['cut_pct']:.1f}% | {r['logrows_base']} -> {r['logrows_opt']} "
                f"| -{r['tiers_dropped']} "
                f"| {rss[0]} -> {rss[1]} |"
            )
    else:
        L.append("No configuration drops a tier.\n")
    L.append("")
    L.append(
        "> Memory figures are the fitted cost model's estimates, not "
        "measurements. Their `confidence` field marks anything above "
        "logrows 21 as extrapolated — see `docs/recon/05_cost_model.md`. "
        f"No memory estimate is displayed for either side above the "
        f"representable limit k={MAX_CIRCUIT_LOGROWS}. The CSV's "
        "`cost_model_logrows_*` fields are clamped inputs to the cost "
        "model; `logrows_*` records the actual row requirement.\n"
    )

    L.append("## Configurations entering the tier budget\n")
    L.append(
        f"The tier budget is `logrows <= {BUDGET_LOGROWS}`, for the "
        "grid's fixed `num_inner_cols=2`. Successful end-to-end runs "
        "must be checked separately in the corresponding results.\n"
    )
    if rescued:
        L.append("| config | rows (base -> opt) | logrows (base -> opt) |")
        L.append("|---|---|---|")
        for r in rescued:
            L.append(
                f"| {r['name']} (L{r['n_layers']}) | {r['rows_base']:,} -> "
                f"{r['rows_opt']:,} | {r['logrows_base']} -> {r['logrows_opt']} |"
            )
        L.append("")
    else:
        L.append("No configuration enters this tier budget.\n")

    L.append("## Baselines within 20% above a tier boundary\n")
    L.append("The required cut includes reserved blinding rows.\n")
    L.append("| config | ratio to tier (base) | needed cut | actual cut | crossed? |")
    L.append("|---|---|---|---|---|")
    for r in sorted(
        near_tier_base, key=lambda r: r["rows_base"] / 2 ** (r["logrows_base"] - 1)
    ):
        thresh = 2 ** (r["logrows_base"] - 1) - estimate_cost.RESERVED_BLINDING_ROWS
        ratio = r["rows_base"] / thresh
        needed = 100.0 * (1 - 1 / ratio)
        L.append(
            f"| {r['name']} (L{r['n_layers']}) | {ratio:.3f} | {needed:.1f}% "
            f"| {r['cut_pct']:.1f}% | {'**yes**' if r['tiers_dropped'] > 0 else 'no'} |"
        )
    L.append("")

    L.append("## Largest configurations within the tier budget\n")
    in_budget = [r for r in joined if r["logrows_opt"] <= BUDGET_LOGROWS]
    in_budget_base = [r for r in joined if r["logrows_base"] <= BUDGET_LOGROWS]
    L.append(
        f"Within `logrows <= {BUDGET_LOGROWS}`: **{len(in_budget_base)} "
        f"configurations before, {len(in_budget)} after.**\n"
    )
    L.append("| config | rows (opt) | logrows (opt) | was in budget? |")
    L.append("|---|---|---|---|")
    for r in sorted(in_budget, key=lambda r: -r["rows_opt"])[:8]:
        L.append(
            f"| {r['name']} (L{r['n_layers']}) | {r['rows_opt']:,} | "
            f"{r['logrows_opt']} | {'yes' if r['logrows_base'] <= BUDGET_LOGROWS else '**no**'} |"
        )
    L.append("")

    L.append("## Full data\n")
    L.append(
        f"`{Path(args.out).with_suffix('.csv').name}` — every configuration measured in "
        "both grids, with rows/logrows before and after.\n"
    )

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L))

    csv_out = out.with_suffix(".csv")
    with open(csv_out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(joined[0].keys()))
        w.writeheader()
        for r in joined:
            r = dict(r)
            r["cut_pct"] = round(r["cut_pct"], 2)
            w.writerow(r)

    print(
        f"{len(joined)} configs compared; {len(crossed)} dropped a tier "
        f"({len(within_limit)} within the circuit limit, "
        f"{len(enter_limit)} entering it, {len(above_limit)} remaining above); "
        f"{len(rescued)} entered the tier budget"
    )
    print(f"wrote {out} and {csv_out}")


if __name__ == "__main__":
    main()
